const gulp = require('gulp');
const fs = require('fs');
const path = require('path');

/**
 * Build brand theme task.
 * Generates brand-specific SCSS variables and copies brand assets.
 */
function buildBrandTheme() {
    return new Promise((resolve, reject) => {
        try {
            // Get brand ID from environment variable or use default
            const brandId = process.env.BRAND_ID || 'default';
            const brandConfigPath = path.join(__dirname, '..', 'branding', brandId, 'brand-config.json');
            const scssOutputPath = path.join(__dirname, '..', 'src', 'theme', 'brand.variables.scss');
            const cssOutputPath = path.join(__dirname, '..', 'src', 'theme', 'brand.custom-properties.scss');

            console.log(`Building brand theme for brand: ${brandId}`);
            console.log(`Source: ${brandConfigPath}`);
            console.log(`SCSS Output: ${scssOutputPath}`);
            console.log(`CSS Output: ${cssOutputPath}`);

            // Check if brand config file exists
            if (!fs.existsSync(brandConfigPath)) {
                console.warn(`Brand config not found: ${brandConfigPath}`);
                console.warn('Falling back to default brand configuration');
                generateDefaultTheme(scssOutputPath, cssOutputPath);
                resolve();
                return;
            }

            // Load brand configuration
            const configContent = fs.readFileSync(brandConfigPath, 'utf8');
            const config = JSON.parse(configContent);

            // Generate SCSS variables
            generateSCSSVariables(config, scssOutputPath);

            // Generate CSS custom properties
            generateCSSCustomProperties(config, cssOutputPath);

            // Copy brand assets
            copyBrandAssets(config, brandId);

            console.log(`Brand theme for '${brandId}' generated successfully`);
            resolve();

        } catch (error) {
            console.error('Failed to build brand theme:', error.message);
            reject(error);
        }
    });
}

/**
 * Generate SCSS variables from brand configuration.
 */
function generateSCSSVariables(config, outputPath) {
    let scssContent = `/*
 * Brand-specific SCSS variables
 * Generated from brand configuration
 * Do not edit this file manually
 */

`;

    if (config.colors) {
        const colors = config.colors;

        // Generate brand color variable
        if (colors.primary) {
            scssContent += `$brand-color: ${colors.primary} !default;\n`;
        }

        // Generate color variables
        if (colors.primary) {
            scssContent += `$primary: ${colors.primary} !default;\n`;
        }
        if (colors.secondary) {
            scssContent += `$secondary: ${colors.secondary} !default;\n`;
        }
        if (colors.surface) {
            scssContent += `$surface: ${colors.surface} !default;\n`;
        }

        // Generate contrast colors
        if (colors.onPrimary) {
            scssContent += `$primary-contrast: ${colors.onPrimary} !default;\n`;
        }
        if (colors.onSecondary) {
            scssContent += `$secondary-contrast: ${colors.onSecondary} !default;\n`;
        }
        if (colors.onSurface) {
            scssContent += `$surface-contrast: ${colors.onSurface} !default;\n`;
        }

        scssContent += `\n`;
    }

    // Write SCSS file
    fs.writeFileSync(outputPath, scssContent);
    console.log(`SCSS variables generated: ${outputPath}`);
}

/**
 * Generate CSS custom properties from brand configuration.
 */
function generateCSSCustomProperties(config, outputPath) {
    let cssContent = `/*
 * Brand-specific CSS custom properties
 * Generated from brand configuration
 * Do not edit this file manually
 */

:root {
`;

    if (config.colors) {
        const colors = config.colors;

        // Generate primary color properties
        if (colors.primary) {
            cssContent += `    --primary: ${colors.primary};\n`;
            cssContent += `    --primary-contrast: ${colors.onPrimary || '#ffffff'};\n`;

            // Generate shade and tint variations
            const variations = generateColorVariations(colors.primary);
            if (variations) {
                cssContent += `    --primary-shade: ${variations.shade};\n`;
                cssContent += `    --primary-tint: ${variations.tint};\n`;
            }
        }

        // Generate secondary color properties
        if (colors.secondary) {
            cssContent += `    --secondary: ${colors.secondary};\n`;
            cssContent += `    --secondary-contrast: ${colors.onSecondary || '#000000'};\n`;

            const variations = generateColorVariations(colors.secondary);
            if (variations) {
                cssContent += `    --secondary-shade: ${variations.shade};\n`;
                cssContent += `    --secondary-tint: ${variations.tint};\n`;
            }
        }

        // Generate surface color properties
        if (colors.surface) {
            cssContent += `    --surface: ${colors.surface};\n`;
            cssContent += `    --surface-contrast: ${colors.onSurface || '#000000'};\n`;
        }
    }

    cssContent += `}\n`;

    // Write CSS file
    fs.writeFileSync(outputPath, cssContent);
    console.log(`CSS custom properties generated: ${outputPath}`);
}

/**
 * Copy brand assets to appropriate locations.
 */
function copyBrandAssets(config, brandId) {
    if (!config.assets) {
        console.log('No brand assets to copy');
        return;
    }

    const assets = config.assets;
    const sourceDir = path.join(__dirname, '..', 'branding', brandId);
    const targetDir = path.join(__dirname, '..', 'src', 'assets', 'brands', brandId);

    // Create target directory if it doesn't exist
    if (!fs.existsSync(targetDir)) {
        fs.mkdirSync(targetDir, { recursive: true });
    }

    // Copy logo
    if (assets.logo) {
        const logoSource = path.join(sourceDir, 'logo.png');
        const logoTarget = path.join(targetDir, 'logo.png');
        if (fs.existsSync(logoSource)) {
            fs.copyFileSync(logoSource, logoTarget);
            console.log(`Logo copied: ${logoTarget}`);
        } else {
            console.warn(`Logo not found: ${logoSource}`);
        }
    }

    // Copy splash
    if (assets.splash) {
        const splashSource = path.join(sourceDir, 'splash.png');
        const splashTarget = path.join(targetDir, 'splash.png');
        if (fs.existsSync(splashSource)) {
            fs.copyFileSync(splashSource, splashTarget);
            console.log(`Splash copied: ${splashTarget}`);
        } else {
            console.warn(`Splash not found: ${splashSource}`);
        }
    }

    // Copy app icon
    if (assets.appIcon) {
        const iconSource = path.join(sourceDir, 'icon.png');
        const iconTarget = path.join(targetDir, 'icon.png');
        if (fs.existsSync(iconSource)) {
            fs.copyFileSync(iconSource, iconTarget);
            console.log(`App icon copied: ${iconTarget}`);
        } else {
            console.warn(`App icon not found: ${iconSource}`);
        }
    }
}

/**
 * Generate default theme when brand config is missing.
 */
function generateDefaultTheme(scssOutputPath, cssOutputPath) {
    // Generate default SCSS variables
    const defaultSCSS = `/*
 * Default brand SCSS variables
 * Generated when no brand configuration is available
 */

$brand-color: #f98012 !default;
$primary: #f98012 !default;
$secondary: #e9ecef !default;
$surface: #ffffff !default;
$primary-contrast: #ffffff !default;
$secondary-contrast: #000000 !default;
$surface-contrast: #282828 !default;
`;

    // Generate default CSS custom properties
    const defaultCSS = `/*
 * Default brand CSS custom properties
 * Generated when no brand configuration is available
 */

:root {
    --primary: #f98012;
    --primary-contrast: #ffffff;
    --primary-shade: #e6730a;
    --primary-tint: #fb8d2a;
    --secondary: #e9ecef;
    --secondary-contrast: #000000;
    --surface: #ffffff;
    --surface-contrast: #282828;
}
`;

    fs.writeFileSync(scssOutputPath, defaultSCSS);
    fs.writeFileSync(cssOutputPath, defaultCSS);
    console.log('Default theme generated');
}

/**
 * Generate color variations for a given color.
 */
function generateColorVariations(hexColor) {
    if (!hexColor || !hexColor.startsWith('#')) {
        return null;
    }

    const cleanHex = hexColor.replace('#', '');
    let r, g, b;

    if (cleanHex.length === 3) {
        // Convert 3-digit hex to 6-digit
        r = parseInt(cleanHex[0] + cleanHex[0], 16);
        g = parseInt(cleanHex[1] + cleanHex[1], 16);
        b = parseInt(cleanHex[2] + cleanHex[2], 16);
    } else {
        r = parseInt(cleanHex.substring(0, 2), 16);
        g = parseInt(cleanHex.substring(2, 4), 16);
        b = parseInt(cleanHex.substring(4, 6), 16);
    }

    // Generate shade (darker)
    const shadeR = Math.max(0, Math.floor(r * 0.8));
    const shadeG = Math.max(0, Math.floor(g * 0.8));
    const shadeB = Math.max(0, Math.floor(b * 0.8));

    // Generate tint (lighter)
    const tintR = Math.min(255, Math.floor(r + (255 - r) * 0.2));
    const tintG = Math.min(255, Math.floor(g + (255 - g) * 0.2));
    const tintB = Math.min(255, Math.floor(b + (255 - b) * 0.2));

    const shade = `#${shadeR.toString(16).padStart(2, '0')}${shadeG.toString(16).padStart(2, '0')}${shadeB.toString(16).padStart(2, '0')}`;
    const tint = `#${tintR.toString(16).padStart(2, '0')}${tintG.toString(16).padStart(2, '0')}${tintB.toString(16).padStart(2, '0')}`;

    return { shade, tint };
}

/**
 * Clean brand theme files.
 */
function cleanBrandTheme() {
    return new Promise((resolve) => {
        const scssPath = path.join(__dirname, '..', 'src', 'theme', 'brand.variables.scss');
        const cssPath = path.join(__dirname, '..', 'src', 'theme', 'brand.custom-properties.scss');
        const assetsDir = path.join(__dirname, '..', 'src', 'assets', 'brands');

        let cleaned = 0;

        if (fs.existsSync(scssPath)) {
            fs.unlinkSync(scssPath);
            console.log('Brand SCSS variables cleaned');
            cleaned++;
        }

        if (fs.existsSync(cssPath)) {
            fs.unlinkSync(cssPath);
            console.log('Brand CSS custom properties cleaned');
            cleaned++;
        }

        if (fs.existsSync(assetsDir)) {
            fs.rmSync(assetsDir, { recursive: true, force: true });
            console.log('Brand assets cleaned');
            cleaned++;
        }

        if (cleaned === 0) {
            console.log('No brand theme files to clean');
        }

        resolve();
    });
}

// Export tasks
module.exports = {
    buildBrandTheme,
    cleanBrandTheme
};
